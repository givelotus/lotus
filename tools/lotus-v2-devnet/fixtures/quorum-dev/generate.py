"""Offline candidate construction; writes only to an explicitly new directory."""
from dataclasses import replace
from hashlib import sha256
import argparse
import importlib.util
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / 'tools/lotus-v2-reference'))
spec = importlib.util.spec_from_file_location('absolute_fixture', HERE.parent / 'reproduce_absolute_fixture.py')
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)
from lotus_v2_reference.asert import Parent as AsertParent, required_bits, compact_decode
from lotus_v2_reference.block import (Parent, Coin, branch_leaf, empty_utxo_root,
    state_root, utxo_root, connect_complete_block, disconnect)
from lotus_v2_reference.block_cost import (BlockCostProfile, authenticated_transaction_costs,
    authenticated_envelope_cost)
from lotus_v2_reference.block_seal import Header, block_id
from lotus_v2_reference.block_wire import complete_transaction_root, encode_block_wire, decode_block_wire
from lotus_v2_reference.encoding import Output
from lotus_v2_reference.header_context import HeaderChainProfile, parent_median_time, validate_child_header
from lotus_v2_reference.monetary import Profile, initialize_genesis, block_cost, required_block_burn, advance
from lotus_v2_reference.signing import Input, Transaction, TxProfile, identity_digests
from lotus_v2_reference.vm import VMProfile, ASSIGNED

NAME = 'lotus-v2-quorum-development-20261015-v1'
RESERVE = 1 << 43
BOOT_SHIFT = 3
STAKE_DUST = 10_000_000_000
QUORUM = 1_000_000_000_000
STAKE_CONFIRMATIONS = 2016
FUNDING_BLOCKS = 9
FINAL_HEIGHT = FUNDING_BLOCKS + STAKE_CONFIRMATIONS - 1

def mine(chain, header, target):
    for nonce in range(100000):
        candidate = replace(header, nonce=nonce)
        if int.from_bytes(block_id(chain, candidate), 'little') <= target:
            return candidate
    raise ValueError('offline deterministic nonce budget exhausted')

def construct():
    source = (HERE.parent / 'local-test-manifest.json').read_bytes()
    provenance = json.loads((HERE.parent / 'provenance.json').read_text())
    assert sha256(source).hexdigest() == provenance['manifest_sha256'] == '0ccb2872198a354e9cdc5e9c91d1816cf65bf8109efc200d86537d65dc660d05'
    assert base.profile_digest(json.loads(source)) == provenance['profile_digest']
    m = json.loads(source)
    chain = base.tagged('Lotus/v2/development-chain', NAME.encode('ascii'))
    m['header']['chain_id'] = chain.hex()
    m['monetary'][0] = BOOT_SHIFT
    mp = Profile(*m['monetary'][:11], int.from_bytes(bytes.fromhex(m['monetary'][11]), 'little'))
    initial = initialize_genesis(mp, bootstrap_reserve=RESERVE, tail_subsidy=mp.genesis_tail,
        genesis_work=mp.genesis_work, ema_block_cost=65536)
    m['initial_monetary'] = initial.to_bytes().hex()
    txp = TxProfile(*m['transaction_limits'])
    h = m['header']; limit = int.from_bytes(bytes.fromhex(h['pow_limit']), 'little')
    hp = HeaderChainProfile(chain, h['version'], h['time'], h['bits'], limit, h['half_life'], h['spacing'])
    note = base.tagged('Lotus/v2/development-genesis-note', NAME.encode('ascii'))
    genesis_tx = Transaction(0, (Input(bytes(32), 0, 0xffffffff, 2),), (Output(2, 0, None, (note,), ()),))
    genesis = mine(chain, Header(bytes(32), h['bits'], h['time'], 0, h['version'], 240, 0,
        complete_transaction_root((genesis_tx,), txp, chain), state_root(chain, 0, empty_utxo_root(), initial)), limit)
    wire = encode_block_wire(genesis, (genesis_tx,), txp)
    decoded = decode_block_wire(wire, txp, chain)
    assert decoded.transactions == (genesis_tx,) and len(wire) == 240
    assert genesis.prev_id == bytes(32) and genesis.height == 0
    assert genesis.state_root == state_root(chain, 0, empty_utxo_root(), initial)
    assert all(o.flags == 2 and o.value == 0 for o in genesis_tx.outputs)
    assert (1 << 256) // (compact_decode(genesis.bits, limit) + 1) == initial.prev_work
    m['genesis'] = wire.hex(); h['genesis_id'] = block_id(chain, genesis).hex()

    # Full reference validation of a first spendable child; scalar-1 public fixture,
    # never a proposed participant key or a secret generated by this program.
    key = bytes.fromhex('79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798')
    leaf = branch_leaf(b'\x20' + key + b'\xbc\x4e')
    cb = Transaction(0, (Input(block_id(chain, genesis), 1, 0xffffffff, 2),),
                     (Output(0, 0, None, (leaf,), ((0,),)),))
    cp = BlockCostProfile(*m['outer_costs'])
    linear = authenticated_transaction_costs(cb, txp, {}, 1, h['time'], 0, cp).account_linear
    cost = block_cost(authenticated_envelope_cost(1, 1, cp), (linear,), mp)
    deduction = max(242, required_block_burn(cost, initial.ema_block_cost, mp))
    payout = (RESERVE >> BOOT_SHIFT) + mp.genesis_tail - deduction
    cb = replace(cb, outputs=(replace(cb.outputs[0], value=payout),))
    transition = advance(mp, initial, work=2, transactions=(), coinbase_native_outputs=payout,
        coinbase_native_burn=0, coinbase_bytes=103, tx_frame_prefix_bytes=1,
        account_block_cost=cost, enforce_block_cost=cost)
    ids = identity_digests(cb, txp, chain)
    coin = Coin(ids.txid, 0, payout, leaf, 1, h['time'], True, cb.outputs[0])
    first = mine(chain, Header(block_id(chain, genesis), h['bits'], h['time']+1, 0, h['version'], 242, 1,
        complete_transaction_root((cb,), txp, chain), state_root(chain, 1, utxo_root({coin.key():coin}), transition.state)), limit)
    vm = VMProfile(*m['vm_limits'][:7], int(m['invocation_limits'][0]), m['invocation_limits'][2],
        {op:(lambda operands, results, row=m['opcode_costs'][op]: row[0]+row[1]*sum(operands)+row[2]*sum(results)) for op in ASSIGNED})
    coins = {}
    accepted = connect_complete_block(encode_block_wire(first, (cb,), txp),
        Parent(chain, 0, h['time'], genesis.state_root, initial, genesis), [genesis], hp,
        coins, initial, mp, cp, tx_profile=txp, vm_profile=vm,
        block_cap=int(m['invocation_limits'][1]), coinbase_maturity=m['coinbase_maturity'])
    assert accepted.monetary_bytes == transition.state.to_bytes()
    assert disconnect(accepted.undo, coins) == initial and not coins

    # Actual ASERT/compact/PoW/MTP verification for a fast header-only schedule.
    # These later headers intentionally do not claim complete-block validity.
    history = [genesis]; max_work = 0; attempts = 0; funding = []; state = initial
    for height in range(1, FINAL_HEIGHT+1):
        parent = history[0]
        time = parent_median_time(hp, parent, history)+1
        bits = required_bits(AsertParent(parent.time, parent.height), t0=h['time'],
            genesis_target=limit, spacing=h['spacing'], half_life=h['half_life'], pow_limit=limit)
        target = compact_decode(bits, limit); work = (1 << 256)//(target+1)
        child = mine(chain, Header(block_id(chain, parent), bits, time, 0, h['version'], 242, height,
            bytes(32), bytes(32)), target)
        validate_child_header(hp, parent, history, child, expected_tx_root=bytes(32),
            expected_state_root=bytes(32), expected_size=242)
        value = max(1, state.bootstrap_reserve >> BOOT_SHIFT) if state.bootstrap_reserve else 0
        paid = value + state.tail_subsidy - max(242, required_block_burn(cost, state.ema_block_cost, mp))
        tr = advance(mp, state, work=work, transactions=(), coinbase_native_outputs=paid,
            coinbase_native_burn=0, coinbase_bytes=103, tx_frame_prefix_bytes=1,
            account_block_cost=cost, enforce_block_cost=cost)
        state = tr.state
        if height <= FUNDING_BLOCKS: funding.append(paid)
        max_work=max(max_work,work); attempts+=child.nonce+1
        history=([child]+history)[:11]
    assert min(funding) >= STAKE_DUST and sum(funding)-max(funding) >= QUORUM
    assert FINAL_HEIGHT-9 == STAKE_CONFIRMATIONS-1
    assert history[0].time-h['time'] < m['future_window']
    report = dict(name=NAME, status='offline development candidate; not adopted or native validated',
        source_manifest_sha256=sha256(source).hexdigest(), chain_id=chain.hex(), genesis_id=h['genesis_id'],
        profile_digest=base.profile_digest(m), bootstrap_reserve=RESERVE, boot_shift=BOOT_SHIFT,
        first_payout=payout, first_block_cost=cost, first_deduction=deduction,
        first_nine_payouts=funding, minimum_any_eight=sum(funding)-max(funding),
        stake_dust=STAKE_DUST, quorum=QUORUM, stake_confirmations=STAKE_CONFIRMATIONS,
        funding_blocks=FUNDING_BLOCKS, mature_tip=FINAL_HEIGHT, connected_neighbors=8,
        schedule_kind='header-only actual ASERT/PoW plus independent monetary transitions',
        schedule_seconds=history[0].time-h['time'], max_work=max_work, nonce_attempts=attempts,
        final_bits=history[0].bits, reserve_at_maturity=state.bootstrap_reserve)
    return m, report

def generate(output):
    manifest, report = construct()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    encoded = (json.dumps(manifest, indent=2)+'\n').encode()
    report['manifest_sha256'] = sha256(encoded).hexdigest()
    (output/'manifest.json').write_bytes(encoded)
    (output/'report.json').write_text(json.dumps(report, indent=2)+'\n')
    return report

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, help='new candidate directory; never an existing node home')
    args=parser.parse_args()
    print(json.dumps(generate(args.output), indent=2))
