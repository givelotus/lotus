#!/usr/bin/env node
// Emit the daemon ordinary-validator fixture header from the signed compiler
// token fixture. The header is an immutable copy pinned by SHA-256; regenerate
// it only through an explicit daemon patch.
//
// Usage: node test/emit-ordinary-fixture-header.mjs [FIXTURE_JSON] > compiler_mint_fixture.h
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const path = process.argv[2] ?? new URL('../fixtures/fungible-token-v2.json', import.meta.url);
const bytes = readFileSync(path);
const fixture = JSON.parse(bytes);
const { mint, transfer, merge } = fixture.transactions;
if (!mint || !transfer || !merge) throw new Error('fixture needs mint, transfer and merge transactions');
if (mint.coinWires[0] === null) throw new Error('mint input 0 must spend a funding coin');
if (new Set([mint.chainId, transfer.chainId, merge.chainId]).size !== 1) throw new Error('chain ID differs between transactions');
const hex = value => { if (!/^[0-9a-f]*$/.test(value)) throw new Error('non-hex fixture field'); return value; };
const line = (name, value) => `inline constexpr const char *${name} = "${hex(value)}";`;
console.log([
  '// Imported immutable compiler fixture from tools/lotus-v2-compiler/fixtures/fungible-token-v2.json',
  `// SHA-256: ${createHash('sha256').update(bytes).digest('hex')}`,
  '// Generated by tools/lotus-v2-compiler/test/emit-ordinary-fixture-header.mjs',
  '#ifndef LOTUS_V2_COMPILER_MINT_FIXTURE_H',
  '#define LOTUS_V2_COMPILER_MINT_FIXTURE_H',
  'namespace compiler_fixture {',
  line('mint_wire', mint.wire), line('mint_txid', mint.txid), line('mint_txhash', mint.txhash),
  line('transfer_wire', transfer.wire), line('transfer_txid', transfer.txid), line('transfer_txhash', transfer.txhash),
  line('merge_wire', merge.wire), line('merge_txid', merge.txid), line('merge_txhash', merge.txhash),
  line('funding_coin_wire', mint.coinWires[0]), line('chain_id', mint.chainId),
  '} // namespace compiler_fixture',
  '#endif',
].join('\n'));
