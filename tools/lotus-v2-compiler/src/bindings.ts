import type { PaymentArtifact } from './compiler.js';
import type { ContractArtifact, ValueType } from './generic.js';

function safeName(name: string): string {
  if (!/^[A-Za-z_][A-Za-z_0-9]*$/.test(name) || new Set('class default function return import export constructor if else true false public private protected static self def None pass'.split(' ')).has(name)) throw new Error('invalid binding name');
  return name;
}
export function generateTypeScript(a: PaymentArtifact): string {
  const n = safeName(a.contract);
  return `// Generated by @lotus/v2-payment-compiler; artifact schema ${a.schema}.\n` +
    `import type { PaymentArtifact } from '@lotus/v2-payment-compiler';\nimport { preparePayment, finalizePayment, type PaymentContext, type PaymentPlan } from '@lotus/v2-payment-compiler/runtime';\n` +
    `export class ${n} {\n  readonly artifact: PaymentArtifact;\n  constructor(artifact: PaymentArtifact) { if (artifact.schema !== 'lotus-v2/payment-artifact/1') throw new Error('artifact version'); this.artifact = artifact; }\n` +
    `  prepareSpend(context: PaymentContext): PaymentPlan { return preparePayment(this.artifact, context); }\n` +
    `  finalizeSpend(plan: PaymentPlan, signature: Uint8Array) { return finalizePayment(plan, signature); }\n}\n`;
}
export function generatePython(a: PaymentArtifact): string {
  const n = safeName(a.contract);
  return `# Generated by @lotus/v2-payment-compiler; artifact schema ${a.schema}.\n` +
    `from dataclasses import dataclass\nfrom typing import Protocol, Mapping, Any\n\n` +
    `class PaymentRuntime(Protocol):\n    def prepare_payment(self, artifact: Mapping[str, Any], context: Mapping[str, Any]) -> Any: ...\n    def finalize_payment(self, plan: Any, signature: bytes) -> Any: ...\n\n` +
    `@dataclass(frozen=True)\nclass ${n}:\n    artifact: Mapping[str, Any]\n    runtime: PaymentRuntime\n\n` +
    `    def __post_init__(self) -> None:\n        if self.artifact.get('schema') != 'lotus-v2/payment-artifact/1':\n            raise ValueError('artifact version')\n\n` +
    `    def prepare_spend(self, context: Mapping[str, Any]) -> Any:\n        return self.runtime.prepare_payment(self.artifact, context)\n\n` +
    `    def finalize_spend(self, plan: Any, signature: bytes) -> Any:\n        if type(signature) is not bytes or len(signature) != 64:\n            raise ValueError('FULL signature must be 64 bytes')\n        return self.runtime.finalize_payment(plan, signature)\n`;
}

function tsType(t: ValueType): string { return t === 'Int' ? 'bigint' : t === 'Bool' ? 'boolean' : t === 'Signature' ? 'null' : 'Uint8Array'; }
export function generateContractTypeScript(a: ContractArtifact): string {
  const contract = safeName(a.contract);
  const lines = [
    `// Generated from ${a.schema}; constructor values and method proofs remain in the artifact.`,
    `import type { ContractArtifact } from '@lotus/v2-payment-compiler/generic';`,
    `import { prepareContractCall, finalizeContractCall, type CallContext, type CallPlan, type CallFinal } from '@lotus/v2-payment-compiler/call-runtime';`,
  ];
  for (const m of a.methods) {
    const name = safeName(m.name); const title = `${contract}${name[0]!.toUpperCase()}${name.slice(1)}`;
    lines.push(`export type ${title}Args = Readonly<{ ${m.args.map(x => `${safeName(x.name)}: ${tsType(x.type)};`).join(' ')} }>;`);
    const signatures = m.args.filter(x => x.type === 'Signature');
    lines.push(`export type ${title}Signatures = Readonly<{ ${signatures.map(x => `${safeName(x.name)}: Uint8Array;`).join(' ')} }>;`);
  }
  lines.push(`export class ${contract} {`, `  readonly artifact: ContractArtifact;`,
    `  constructor(artifact: ContractArtifact) { if (artifact.schema !== 'lotus-v2/contract-artifact/2' || artifact.contract !== '${contract}') throw new Error('artifact identity'); this.artifact = artifact; }`);
  for (const m of a.methods) {
    const name = safeName(m.name), title = `${contract}${name[0]!.toUpperCase()}${name.slice(1)}`;
    lines.push(`  prepare${name[0]!.toUpperCase()}${name.slice(1)}(context: CallContext, args: ${title}Args): CallPlan { return prepareContractCall(this.artifact, '${name}', context, args); }`,
      `  finalize${name[0]!.toUpperCase()}${name.slice(1)}(plan: CallPlan, signatures: ${title}Signatures): CallFinal { if (plan.methodName !== '${name}') throw new Error('method plan mismatch'); return finalizeContractCall(plan, signatures); }`);
  }
  lines.push('}', ''); return lines.join('\n');
}
